//! `djc --completions fish`: the fish completion script, GENERATED from the verb
//! tables rather than hand-written, so it cannot rot when a verb is added. The
//! routed verbs come from `route::ROUTED_VERBS` (pinned against the router bodies by
//! route.rs's own tests); the CLI-only verbs that `lib.rs` intercepts before
//! `route()` live in `CLI_VERBS` here, pinned against lib.rs by the test below.

use hypodj_client::route::{VerbSpec, ROUTED_VERBS};

/// Verbs the `djc` CLI claims BEFORE `route()` (stations/heard/store/journal/undo),
/// with the subcommand words their own parsers accept. Where a word is also routed
/// (`heard`, `store`), these args are merged with the routed ones.
pub const CLI_VERBS: &[VerbSpec] = &[
    VerbSpec {
        word: "stations",
        args: &["import", "rm", "list"],
        help: "manage radio stations (.pls import)",
    },
    VerbSpec {
        word: "heard",
        args: &["all", "marks", "limit", "keep", "drop"],
        help: "what played tonight",
    },
    VerbSpec {
        word: "store",
        args: &[
            "status", "show", "frontier", "pause", "resume", "now", "limit",
        ],
        help: "offline store status and control",
    },
    VerbSpec {
        word: "journal",
        args: &[],
        help: "what the daemon did, newest first",
    },
    VerbSpec {
        word: "undo",
        args: &[],
        help: "retract the newest retractable action",
    },
];

/// The merged first-word set, in table order, each word once with its arg union.
fn merged() -> Vec<(&'static str, Vec<&'static str>, &'static str)> {
    let mut out: Vec<(&str, Vec<&str>, &str)> = Vec::new();
    for v in ROUTED_VERBS.iter().chain(CLI_VERBS) {
        match out.iter_mut().find(|(w, _, _)| *w == v.word) {
            Some((_, args, _)) => {
                for a in v.args {
                    if !args.contains(a) {
                        args.push(a);
                    }
                }
            }
            None => out.push((v.word, v.args.to_vec(), v.help)),
        }
    }
    out
}

/// The same script for the command named `cmd` (`djc`, or `dj`, which falls back to
/// `djc` whenever it is given arguments, so it completes the same verbs).
pub fn fish_for(cmd: &str) -> String {
    fish()
        .replace("complete -c djc ", &format!("complete -c {cmd} "))
        .replacen("# djc fish", &format!("# {cmd} fish"), 1)
        .replacen("`djc --completions", &format!("`{cmd} --completions"), 1)
}

pub fn fish() -> String {
    let mut s = String::from(
        "# djc fish completions - generated by `djc --completions fish`, do not edit.\n\
         complete -c djc -f\n\
         complete -c djc -l host -x -d 'daemon host'\n\
         complete -c djc -l port -x -d 'daemon port'\n\
         complete -c djc -l nl-translator -x -a 'auto rules daemon claude cc' -d 'pin the NL path'\n\
         complete -c djc -s h -l help -d 'show help'\n\
         complete -c djc -s V -l version -d 'print version'\n\
         complete -c djc -l completions -x -a fish -d 'print shell completions'\n",
    );
    let all: Vec<&str> = merged().iter().map(|(w, _, _)| *w).collect();
    for (word, args, help) in merged() {
        s.push_str(&format!(
            "complete -c djc -n 'not __fish_seen_subcommand_from {}' -a {word} -d '{help}'\n",
            all.join(" ")
        ));
        if !args.is_empty() {
            s.push_str(&format!(
                "complete -c djc -n '__fish_seen_subcommand_from {word}; and not __fish_seen_subcommand_from {}' -a '{}'\n",
                args.join(" "),
                args.join(" ")
            ));
        }
    }
    // `stations import` takes .pls paths.
    s.push_str("complete -c djc -n '__fish_seen_subcommand_from stations; and __fish_seen_subcommand_from import' -F\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every verb lib.rs intercepts before route() (`w == "x"`) is in CLI_VERBS.
    #[test]
    fn every_intercepted_cli_verb_is_listed() {
        let src = include_str!("lib.rs");
        let mut found = Vec::new();
        for part in src.split("w == \"").skip(1) {
            found.push(&part[..part.find('"').unwrap()]);
        }
        assert!(found.len() >= 5, "scanner found too little: {found:?}");
        for w in found {
            assert!(
                CLI_VERBS.iter().any(|v| v.word == w),
                "intercepted `{w}` missing from CLI_VERBS"
            );
        }
    }

    #[test]
    fn dj_script_is_the_djc_script_under_its_own_name() {
        let (djc, dj) = (fish(), fish_for("dj"));
        assert!(!dj.contains("-c djc "), "{dj}");
        assert_eq!(dj.matches("complete -c dj ").count(), djc.matches("complete -c djc ").count());
        assert_eq!(fish_for("djc"), djc);
    }

    #[test]
    fn script_offers_every_verb_and_its_args_once() {
        let s = fish();
        for v in ROUTED_VERBS.iter().chain(CLI_VERBS) {
            assert_eq!(
                s.matches(&format!(" -a {} -d ", v.word)).count(),
                1,
                "{}",
                v.word
            );
            if let Some(line) = s
                .lines()
                .find(|l| l.contains(&format!("from {}; and", v.word)))
            {
                for a in v.args {
                    assert!(
                        line.split('\'').nth(3).unwrap().split(' ').any(|w| w == *a),
                        "{} {a}",
                        v.word
                    );
                }
            } else {
                assert!(v.args.is_empty(), "{} has args but no arg line", v.word);
            }
        }
        // No help text may break the single-quoted fish string.
        assert!(ROUTED_VERBS
            .iter()
            .chain(CLI_VERBS)
            .all(|v| !v.help.contains('\'')));
    }
}
